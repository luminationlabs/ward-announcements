#!/usr/bin/env node
// Regenerate src/hymns.ts — the hymn number → page table behind the program's hymn links (see
// "Hymn links" in src/markdown.ts). Run by hand when the Church publishes new hymns:
//
//     npm run hymns
//
// It fetches the two hymnbook index pages on churchofjesuschrist.org, reads each entry's number
// *as the page prints it* (the `songNumber` span inside every hymn link) together with the link's
// page slug, and writes the table. Numbers are never inferred from list order, and a page address
// is never derived from a title: an entry the index does not show with a number is not in the table.
//
// Behind an HTTP proxy, Node's fetch ignores HTTPS_PROXY unless asked: NODE_USE_ENV_PROXY=1 npm run hymns
//
// Deliberately not part of `npm run build`: the build stays offline and reproducible, and the table
// is committed, so a change to it is a reviewed diff rather than something a deploy picks up.
//
// Fails loudly (non-zero exit, nothing written) when either page parses to far fewer entries than
// expected — the sign that the site's markup changed and this parser needs updating, which must not
// quietly shrink the table.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ORIGIN = 'https://www.churchofjesuschrist.org';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'hymns.ts');

const BOOKS = [
  {
    name: 'HYMNS_1985',
    title: 'Hymns (1985)',
    path: '/study/manual/hymns',
    // 341 numbered hymns; the book is closed, so anything well short of that is a parse failure.
    min: 330,
  },
  {
    name: 'HYMNS_FOR_HOME_AND_CHURCH',
    title: 'Hymns—For Home and Church',
    path: '/study/music/hymns-for-home-and-church',
    // Still being released in batches, so the floor is what had been published when this was written.
    min: 75,
  },
];

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

async function fetchIndex(path) {
  const res = await fetch(`${ORIGIN}${path}?lang=eng`, {
    headers: { 'user-agent': 'Mozilla/5.0 (ward-announcements hymn-index script)' },
  });
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.text();
}

/**
 * Every `<a href="<path>/<slug>?lang=eng">…<span class="songNumber-…">N</span>…</a>` on the page.
 * The same link appears more than once (table of contents and body), so entries are collected by
 * number; a number that points at two different slugs is a conflict and stops the run.
 */
function parseIndex(html, path) {
  const linkRe = new RegExp(
    `<a\\b[^>]*\\bhref="${escapeRe(path)}/([a-z0-9-]+)\\?lang=eng"[^>]*>([\\s\\S]*?)</a>`,
    'g',
  );
  const byNumber = new Map();
  let unnumbered = 0;
  for (const [, slug, inner] of html.matchAll(linkRe)) {
    const num = /class="songNumber[^"]*"[^>]*>\s*(\d+)\s*</.exec(inner)?.[1];
    if (!num) {
      unnumbered++;
      continue;
    }
    const n = Number(num);
    const seen = byNumber.get(n);
    if (seen && seen !== slug) throw new Error(`${path}: #${n} links to both ${seen} and ${slug}`);
    byNumber.set(n, slug);
  }
  return { byNumber, unnumbered };
}

/** Runs of missing numbers between the lowest and highest, as "a–b" strings. */
function gaps(numbers) {
  const out = [];
  for (let i = 1; i < numbers.length; i++) {
    const [a, b] = [numbers[i - 1], numbers[i]];
    if (b - a > 1) out.push(b - a === 2 ? `${a + 1}` : `${a + 1}–${b - 1}`);
  }
  return out;
}

const tables = [];
for (const book of BOOKS) {
  const { byNumber, unnumbered } = parseIndex(await fetchIndex(book.path), book.path);
  const numbers = [...byNumber.keys()].sort((a, b) => a - b);
  console.log(
    `${book.title}: ${numbers.length} hymns, #${numbers[0]}–#${numbers.at(-1)}` +
      (gaps(numbers).length ? `, gaps ${gaps(numbers).join(', ')}` : ', no gaps') +
      (unnumbered ? ` (${unnumbered} unnumbered links ignored)` : ''),
  );
  if (numbers.length < book.min) {
    console.error(
      `\n${book.path}: parsed only ${numbers.length} numbered hymns (expected at least ${book.min}).` +
        `\nThe page's markup has probably changed; src/hymns.ts was NOT written.`,
    );
    process.exit(1);
  }
  tables.push({ ...book, numbers, byNumber });
}

const today = new Date().toISOString().slice(0, 10);
const body = tables
  .map(
    (t) =>
      `/** ${t.title}: ${ORIGIN}${t.path}/<slug>?lang=eng (${t.numbers.length} hymns). */\n` +
      `export const ${t.name}: Readonly<Record<number, string>> = {\n` +
      t.numbers.map((n) => `  ${n}: '${t.byNumber.get(n)}',`).join('\n') +
      `\n};\n`,
  )
  .join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/hymn-index.mjs on ${today} — do not edit by hand.
// Regenerate with \`npm run hymns\` (fetches the two hymnbook index pages on
// www.churchofjesuschrist.org and reads each hymn's number as the page prints it).
//
// Hymn number → page slug for each hymnbook, used by the program renderer's hymn links
// (src/markdown.ts). A number missing here is linked to its book's index page instead.

${body}`,
);
console.log(`Wrote ${OUT}`);
